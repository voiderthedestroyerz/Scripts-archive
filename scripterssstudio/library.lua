local Players     = game:GetService("Players")
local LocalPlayer = Players.LocalPlayer
local PlayerGui   = LocalPlayer:WaitForChild("PlayerGui")

local Library = (function()
	local CONFIG = {
		DiscordLink = "https://discord.gg/GNYmtZMwKB",
		Credits     = "Credits:VOIDERTHEDESTROYER",
	}

	local Lib          = {}
	local userPages    = {}
	local settingsPage = nil
	local currentPage  = 1

	local function frameGradient()
		return ColorSequence.new{
			ColorSequenceKeypoint.new(0.000, Color3.fromRGB(0, 0, 0)),
			ColorSequenceKeypoint.new(0.535, Color3.fromRGB(0, 0, 0)),
			ColorSequenceKeypoint.new(1.000, Color3.fromRGB(255, 90, 7)),
		}
	end

	local function buttonGradient()
		return ColorSequence.new{
			ColorSequenceKeypoint.new(0.000, Color3.fromRGB(255, 255, 255)),
			ColorSequenceKeypoint.new(0.535, Color3.fromRGB(255, 255, 255)),
			ColorSequenceKeypoint.new(1.000, Color3.fromRGB(255, 90, 7)),
		}
	end

	local ScreenGui = Instance.new("ScreenGui")
	ScreenGui.Name           = "main"
	ScreenGui.ZIndexBehavior = Enum.ZIndexBehavior.Sibling
	ScreenGui.ResetOnSpawn   = false
	ScreenGui.Parent         = PlayerGui

	local MainFrame = Instance.new("Frame")
	MainFrame.BorderSizePixel  = 0
	MainFrame.BackgroundColor3 = Color3.fromRGB(255, 255, 255)
	MainFrame.Size             = UDim2.new(0, 419, 0, 286)
	MainFrame.Position         = UDim2.new(0.3753, 0, 0.31429, 0)
	MainFrame.BorderColor3     = Color3.fromRGB(0, 0, 0)
	MainFrame.Active           = true
	MainFrame.Parent           = ScreenGui
	Instance.new("UIGradient", MainFrame).Color = frameGradient()

	local Logo = Instance.new("ImageLabel", MainFrame)
	Logo.BorderSizePixel        = 0
	Logo.BackgroundColor3       = Color3.fromRGB(255, 255, 255)
	Logo.Image                  = "rbxassetid://132194807654911"
	Logo.Size                   = UDim2.new(0, 54, 0, 51)
	Logo.BorderColor3           = Color3.fromRGB(0, 0, 0)
	Logo.BackgroundTransparency = 1
	Logo.ZIndex                 = 10

	local Title = Instance.new("TextLabel", MainFrame)
	Title.TextWrapped            = true
	Title.BorderSizePixel        = 0
	Title.TextSize               = 14
	Title.TextScaled             = true
	Title.BackgroundColor3       = Color3.fromRGB(255, 255, 255)
	Title.FontFace               = Font.new("rbxasset://fonts/families/SourceSansPro.json", Enum.FontWeight.Regular, Enum.FontStyle.Normal)
	Title.TextColor3             = Color3.fromRGB(255, 255, 255)
	Title.BackgroundTransparency = 1
	Title.Size                   = UDim2.new(0, 200, 0, 51)
	Title.BorderColor3           = Color3.fromRGB(0, 0, 0)
	Title.Text                   = "Scripters Studio"
	Title.Position               = UDim2.new(0.11217, 0, 0, 0)
	Title.ZIndex                 = 10
	Instance.new("UIGradient", Title).Color = buttonGradient()

	-- Dragging
	do
		local dragging, dragStart, startPos

		MainFrame.InputBegan:Connect(function(input)
			if input.UserInputType == Enum.UserInputType.MouseButton1
			or input.UserInputType == Enum.UserInputType.Touch then
				dragging  = true
				dragStart = input.Position
				startPos  = MainFrame.Position

				input.Changed:Connect(function()
					if input.UserInputState == Enum.UserInputState.End then
						dragging = false
					end
				end)
			end
		end)

		MainFrame.InputChanged:Connect(function(input)
			if input.UserInputType == Enum.UserInputType.MouseMovement
			or input.UserInputType == Enum.UserInputType.Touch then
				if dragging then
					local delta = input.Position - dragStart
					MainFrame.Position = UDim2.new(
						startPos.X.Scale, startPos.X.Offset + delta.X,
						startPos.Y.Scale, startPos.Y.Offset + delta.Y
					)
				end
			end
		end)
	end

	local function totalPages()
		return #userPages + (settingsPage and 1 or 0)
	end

	local function pageAt(index)
		if index <= #userPages then return userPages[index] end
		if settingsPage and index == #userPages + 1 then return settingsPage end
	end

	local function refreshVisibility()
		for i = 1, totalPages() do
			local p = pageAt(i)
			if p then p.Visible = (i == currentPage) end
		end
	end

	local COL_X = {0.02387, 0.27446, 0.52745, 0.7685}
	local COL_W = {97, 97, 97, 88}

	local function makeNavButton(text, xPos, parent)
		local b = Instance.new("TextButton", parent)
		b.TextWrapped      = true
		b.BorderSizePixel  = 0
		b.TextSize         = 14
		b.TextScaled       = true
		b.TextColor3       = Color3.fromRGB(0, 0, 0)
		b.BackgroundColor3 = Color3.fromRGB(255, 255, 255)
		b.FontFace         = Font.new("rbxasset://fonts/families/SourceSansPro.json", Enum.FontWeight.Regular, Enum.FontStyle.Normal)
		b.Size             = UDim2.new(0, 77, 0, 37)
		b.BorderColor3     = Color3.fromRGB(0, 0, 0)
		b.Text             = text
		b.Position         = UDim2.new(xPos, 0, 0.81624, 0)
		b.ZIndex           = 5
		Instance.new("UIGradient", b).Color = buttonGradient()
		return b
	end

	local function makePage(name)
		local page = Instance.new("Frame", MainFrame)
		page.Name             = name
		page.BorderSizePixel  = 0
		page.BackgroundColor3 = Color3.fromRGB(255, 255, 255)
		page.Size             = UDim2.new(0, 419, 0, 234)
		page.Position         = UDim2.new(0.0006, 0, 0.17832, 0)
		page.BorderColor3     = Color3.fromRGB(0, 0, 0)
		page.Visible          = false
		Instance.new("UIGradient", page).Color = frameGradient()

		local scroll = Instance.new("ScrollingFrame", page)
		scroll.Name                   = "Content"
		scroll.BackgroundTransparency = 1
		scroll.BorderSizePixel        = 0
		scroll.Position               = UDim2.new(0, 0, 0, 0)
		scroll.Size                   = UDim2.new(1, 0, 0, 190)
		scroll.CanvasSize             = UDim2.new(0, 0, 0, 0)
		scroll.ScrollBarThickness     = 3
		scroll.ScrollBarImageColor3   = Color3.fromRGB(255, 90, 7)
		scroll.ScrollingDirection     = Enum.ScrollingDirection.Y

		local prev = makeNavButton("<", 0.02387, page)
		local next = makeNavButton(">", 0.79475, page)

		prev.MouseButton1Click:Connect(function()
			if currentPage > 1 then
				currentPage -= 1
				refreshVisibility()
			end
		end)
		next.MouseButton1Click:Connect(function()
			if currentPage < totalPages() then
				currentPage += 1
				refreshVisibility()
			end
		end)

		return page, scroll
	end

	local function addGridButton(scroll, text, callback, index)
		local row = math.floor((index - 1) / 4)
		local col = ((index - 1) % 4) + 1

		local b = Instance.new("TextButton", scroll)
		b.TextWrapped      = true
		b.BorderSizePixel  = 0
		b.TextSize         = 14
		b.TextScaled       = true
		b.TextColor3       = Color3.fromRGB(0, 0, 0)
		b.BackgroundColor3 = Color3.fromRGB(255, 255, 255)
		b.FontFace         = Font.new("rbxasset://fonts/families/SourceSansPro.json", Enum.FontWeight.Regular, Enum.FontStyle.Normal)
		b.Size             = UDim2.new(0, COL_W[col], 0, 37)
		b.BorderColor3     = Color3.fromRGB(0, 0, 0)
		b.Text             = text
		b.Position         = UDim2.new(COL_X[col], 0, 0, row * 45)
		Instance.new("UIGradient", b).Color = buttonGradient()

		local neededHeight = (row + 1) * 45
		if scroll.CanvasSize.Y.Offset < neededHeight then
			scroll.CanvasSize = UDim2.new(0, 0, 0, neededHeight)
		end

		if callback then
			b.MouseButton1Click:Connect(function()
				local ok, err = pcall(callback)
				if not ok then warn("[Scripters Studio] Button error: " .. tostring(err)) end
			end)
		end
		return b
	end

	function Lib:CreatePage(name)
		local page, scroll = makePage(name)
		table.insert(userPages, page)

		local api, count = {}, 0
		function api:AddButton(text, callback)
			count += 1
			return addGridButton(scroll, text, callback, count)
		end

		refreshVisibility()
		return api
	end

	function Lib:SetDiscordLink(link) CONFIG.DiscordLink = link end
	function Lib:SetCredits(text)     CONFIG.Credits     = text end
	function Lib:Open()   currentPage = 1; refreshVisibility(); ScreenGui.Enabled = true end
	function Lib:Close()  ScreenGui.Enabled = false end
	function Lib:Toggle() ScreenGui.Enabled = not ScreenGui.Enabled end
	function Lib:Destroy() ScreenGui:Destroy() end

	-- Settings page (always last)
	do
		local page, scroll = makePage("Settings")
		scroll.Visible = false

		local credits = Instance.new("TextLabel", page)
		credits.TextWrapped            = true
		credits.BorderSizePixel        = 0
		credits.TextSize               = 14
		credits.TextScaled             = true
		credits.BackgroundColor3       = Color3.fromRGB(255, 255, 255)
		credits.FontFace               = Font.new("rbxasset://fonts/families/SourceSansPro.json", Enum.FontWeight.Regular, Enum.FontStyle.Normal)
		credits.TextColor3             = Color3.fromRGB(255, 255, 255)
		credits.BackgroundTransparency = 1
		credits.Size                   = UDim2.new(0, 255, 0, 51)
		credits.BorderColor3           = Color3.fromRGB(0, 0, 0)
		credits.Text                   = CONFIG.Credits
		credits.Position               = UDim2.new(0.02387, 0, 0.05, 0)
		credits.ZIndex                 = 2
		Instance.new("UIGradient", credits).Color = buttonGradient()

		local discordBtn = Instance.new("TextButton", page)
		discordBtn.TextWrapped      = true
		discordBtn.BorderSizePixel  = 0
		discordBtn.TextSize         = 14
		discordBtn.TextScaled       = true
		discordBtn.TextColor3       = Color3.fromRGB(0, 0, 0)
		discordBtn.BackgroundColor3 = Color3.fromRGB(255, 255, 255)
		discordBtn.FontFace         = Font.new("rbxasset://fonts/families/SourceSansPro.json", Enum.FontWeight.Regular, Enum.FontStyle.Normal)
		discordBtn.Size             = UDim2.new(0, 254, 0, 37)
		discordBtn.BorderColor3     = Color3.fromRGB(0, 0, 0)
		discordBtn.Text             = "Copy discord server invite"
		discordBtn.Position         = UDim2.new(0.02387, 0, 0.4, 0)
		discordBtn.ZIndex           = 2
		Instance.new("UIGradient", discordBtn).Color = buttonGradient()

		discordBtn.MouseButton1Click:Connect(function()
			local copied = false
			if typeof(setclipboard) == "function" then
				copied = pcall(setclipboard, CONFIG.DiscordLink)
			elseif typeof(syn) == "table" and typeof(syn.writeclipboard) == "function" then
				copied = pcall(syn.writeclipboard, CONFIG.DiscordLink)
			elseif typeof(fluxus) == "table" and typeof(fluxus.setclipboard) == "function" then
				copied = pcall(fluxus.setclipboard, CONFIG.DiscordLink)
			end
			discordBtn.Text = copied and "Copied to clipboard!" or "Clipboard unavailable"
			task.wait(1.5)
			discordBtn.Text = "Copy discord server invite"
		end)

		settingsPage = page
		refreshVisibility()
	end

	-- Notifications
	local NotifyGui = Instance.new("ScreenGui")
	NotifyGui.Name           = "Notifications"
	NotifyGui.ZIndexBehavior = Enum.ZIndexBehavior.Sibling
	NotifyGui.ResetOnSpawn   = false
	NotifyGui.DisplayOrder   = 999
	NotifyGui.Parent         = PlayerGui

	local activeNotifications = 0

	function Lib:Notify(titleText, bodyText)
		activeNotifications += 1
		local slot = activeNotifications

		local frame = Instance.new("Frame")
		frame.BorderSizePixel  = 0
		frame.BackgroundColor3 = Color3.fromRGB(255, 255, 255)
		frame.Size             = UDim2.new(0, 235, 0, 54)
		frame.Position         = UDim2.new(0.5, 300, 0, 20 + (slot - 1) * 62)
		frame.BorderColor3     = Color3.fromRGB(0, 0, 0)
		frame.Name             = "page1"
		frame.Parent           = NotifyGui

		Instance.new("UIGradient", frame).Color = frameGradient()

		local icon = Instance.new("ImageLabel", frame)
		icon.BorderSizePixel        = 0
		icon.BackgroundColor3       = Color3.fromRGB(255, 255, 255)
		icon.Image                  = "rbxassetid://132194807654911"
		icon.Size                   = UDim2.new(0, 38, 0, 33)
		icon.BorderColor3           = Color3.fromRGB(0, 0, 0)
		icon.BackgroundTransparency = 1

		local title = Instance.new("TextLabel", frame)
		title.TextWrapped            = true
		title.BorderSizePixel        = 0
		title.TextSize               = 14
		title.TextScaled             = true
		title.BackgroundColor3       = Color3.fromRGB(255, 255, 255)
		title.FontFace               = Font.new("rbxasset://fonts/families/SourceSansPro.json", Enum.FontWeight.Regular, Enum.FontStyle.Normal)
		title.TextColor3             = Color3.fromRGB(255, 255, 255)
		title.BackgroundTransparency = 1
		title.Size                   = UDim2.new(0, 188, 0, 24)
		title.BorderColor3           = Color3.fromRGB(0, 0, 0)
		title.Text                   = titleText
		title.Position               = UDim2.new(0.1617, 0, 0, 0)
		Instance.new("UIGradient", title).Color = buttonGradient()

		local body = Instance.new("TextLabel", frame)
		body.TextWrapped            = true
		body.BorderSizePixel        = 0
		body.TextSize               = 14
		body.TextScaled             = true
		body.BackgroundColor3       = Color3.fromRGB(255, 255, 255)
		body.FontFace               = Font.new("rbxasset://fonts/families/SourceSansPro.json", Enum.FontWeight.Regular, Enum.FontStyle.Normal)
		body.TextColor3             = Color3.fromRGB(255, 255, 255)
		body.BackgroundTransparency = 1
		body.Size                   = UDim2.new(0, 188, 0, 24)
		body.BorderColor3           = Color3.fromRGB(0, 0, 0)
		body.Text                   = bodyText
		body.Position               = UDim2.new(0.1617, 0, 0.44444, 0)
		Instance.new("UIGradient", body).Color = buttonGradient()

		frame:TweenPosition(
			UDim2.new(0.5, 300 - 250, 0, 20 + (slot - 1) * 62),
			Enum.EasingDirection.Out, Enum.EasingStyle.Quad, 0.3, true
		)

		task.delay(2.5, function()
			frame:TweenPosition(
				UDim2.new(0.5, 300, 0, 20 + (slot - 1) * 62),
				Enum.EasingDirection.In, Enum.EasingStyle.Quad, 0.3, true
			)
			task.wait(0.35)
			frame:Destroy()
			activeNotifications = math.max(0, activeNotifications - 1)
		end)
	end

	return Lib
end)()

return Library
